package preflight

import (
	"os"
	"path/filepath"
	"testing"
)

func TestDetectGooseHeader(t *testing.T) {
	if !DetectGooseHeader([]byte("// 由 Goose 生成——真源是 config.yaml")) {
		t.Fatalf("should detect goose header")
	}
	if !DetectGooseHeader([]byte("# generated by goose")) {
		t.Fatalf("should detect generated-by-goose")
	}
	if DetectGooseHeader([]byte("routing { }")) {
		t.Fatalf("should not detect")
	}
}

func TestCheckSubscriptions(t *testing.T) {
	dir := t.TempDir()
	cfg := filepath.Join(dir, "config.dae")
	// 绝对路径 -> 报错
	errs, _ := CheckSubscriptions(cfg, []byte("subscription { url: 'file:///etc/dae/subs/x.sub' }"))
	if len(errs) == 0 {
		t.Fatalf("absolute file:// should error (R2)")
	}
	// 相对路径但文件不存在 -> 报错
	errs, _ = CheckSubscriptions(cfg, []byte("subscription { url: 'file://subs/missing.sub' }"))
	if len(errs) == 0 {
		t.Fatalf("missing sub file should error")
	}
	// 相对路径且存在 -> 无错
	if err := os.MkdirAll(filepath.Join(dir, "subs"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "subs", "ok.sub"), []byte("ss://x"), 0o600); err != nil {
		t.Fatal(err)
	}
	errs, _ = CheckSubscriptions(cfg, []byte("subscription { url: 'file://subs/ok.sub' }"))
	if len(errs) != 0 {
		t.Fatalf("valid sub should have no errors, got %v", errs)
	}
}

func TestCheckSubscriptionsEmptyNote(t *testing.T) {
	dir := t.TempDir()
	cfg := filepath.Join(dir, "config.dae")
	_, notes := CheckSubscriptions(cfg, []byte("global { }"))
	if len(notes) == 0 {
		t.Fatalf("expected empty-config note (R1)")
	}
}

func TestBlockingLogic(t *testing.T) {
	r := Report{GooseHeader: true, GooseInstalled: true}
	if !r.Blocking() {
		t.Fatalf("goose header+installed should block")
	}
	r = Report{GooseRunning: []int{123}}
	if !r.Blocking() {
		t.Fatalf("goose running should block")
	}
	r = Report{OtherWriters: []Writer{{PID: 1}}}
	if !r.Blocking() {
		t.Fatalf("other writers should block")
	}
	r = Report{}
	if r.Blocking() {
		t.Fatalf("clean report should not block")
	}
}
